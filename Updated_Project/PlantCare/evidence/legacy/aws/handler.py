"""Prototype AWS Lambda handler; never emits pump commands. Durable idempotency/state to be completed."""
import json,os,datetime
from pathlib import Path
from .analysis import assess
from .contracts import validate_telemetry
from .model import load_demo_model

PROFILE=json.loads((Path(__file__).resolve().parents[1]/'profiles'/'pothos.json').read_text())
PREFIX='plantcare/team3/'

def process_packet(event,profile=PROFILE):
    p=validate_telemetry(event)
    if p['mode']=='live' and p['device_id'].startswith('sim-'):raise ValueError('simulation source on live payload')
    use_demo_model = p['mode'] == 'simulated' and os.getenv('ENABLE_SYNTHETIC_MODEL') == 'true'
    if use_demo_model:
        profile = {**profile, 'classification': {**profile.get('classification', {}), 'model_enabled': True}}
    outcome=assess(p,profile,model=load_demo_model() if use_demo_model else None)
    now=datetime.datetime.now(datetime.timezone.utc).isoformat(timespec='milliseconds').replace('+00:00','Z')
    return {'schema':1,'mode':p['mode'],'profile':p.get('profile','normal'),
      'ts':now,'report_seq':p['seq'],'backend_boot_id':'lambda-prototype',
      'profile_revision':profile['revision'],'sample_ts':p['ts'],
      'source':{'device_id':p['device_id'],'boot_id':p['boot_id'],'seq':p['seq']},
      'freshness_timeout_s':180,'data_status':outcome['data_status'],'invalid_fields':[],
      'state':outcome['state'],'mood':outcome['mood'],'issues':outcome['issues'],
      'reason':outcome['reason'],'details':[],
      'watering':{'stage':'DISARMED','pump_on':False,'command_id':None,'cooldown_remaining_s':0,'fault':None}}

def lambda_handler(event,context):
    expected_mode = os.getenv('EXPECTED_MODE')
    if expected_mode and (not isinstance(event, dict) or event.get('mode') != expected_mode):
        raise ValueError('telemetry mode does not match IoT rule')
    report=process_packet(event)
    if os.environ.get('DRY_RUN','true').lower()!='false':return {'dry_run':True,'report':report}
    import boto3
    table = os.getenv('HISTORY_TABLE')
    if table:
        boto3.client('dynamodb').put_item(
            TableName=table,
            Item={
                'device': {'S': json.dumps([event['mode'], event['device_id']])},
                'sample': {'S': json.dumps([event['boot_id'], event['seq']])},
                'ts': {'S': event['ts']},
                'telemetry': {'S': json.dumps(event, allow_nan=False)},
            },
        )
    endpoint=os.environ['IOT_DATA_ENDPOINT']
    client=boto3.client('iot-data',endpoint_url='https://'+endpoint)
    mode=event['mode'];prefix=PREFIX+('pothos1/' if mode=='live' else 'sim/pothos1/')
    # No command is ever generated by this prototype.
    client.publish(topic=prefix+'condition',qos=1,retain=True,payload=json.dumps(report).encode())
    return {'dry_run':False,'report':report}
